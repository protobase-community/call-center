-- The call center's customers and their tickets. Names, email addresses and phone numbers are plain text, as people
-- write them anywhere in the world; a phone number is shown, never used to tell who a caller is.

create extension if not exists pg_trgm;

-- The number a caller keys on the phone; staff may type one of their own instead.
create sequence public.customer_numbers start 100001;

create table public.customers (
  id integer generated by default as identity primary key,
  name text not null check (length(name) between 1 and 200),
  customer_number text not null default nextval('public.customer_numbers')::text unique
    check (customer_number ~ '^[0-9]{1,20}$'),
  email text check (length(email) <= 320),
  phone text check (length(phone) <= 40),
  created_at timestamptz not null default now()
);

alter sequence public.customer_numbers owned by public.customers.customer_number;

create index customers_name on public.customers (name);
create index customers_email on public.customers (email);
create index customers_created_at on public.customers (created_at);
create index customers_name_search on public.customers using gin (name gin_trgm_ops);
create index customers_email_search on public.customers using gin (email gin_trgm_ops);
create index customers_customer_number_search on public.customers using gin (customer_number gin_trgm_ops);
create index customers_phone_digits on public.customers using gin (regexp_replace(phone, '[^0-9]', '', 'g') gin_trgm_ops);

create table public.tickets (
  id integer generated by default as identity primary key,
  customer_id integer not null references public.customers (id),
  subject text not null check (length(subject) between 1 and 200),
  description text,
  status text not null check (status in ('open', 'pending', 'solved')),
  -- NULL until someone sets it.
  priority text check (priority in ('low', 'normal', 'high', 'urgent')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index tickets_customer_id on public.tickets (customer_id);
create index tickets_status on public.tickets (status);
create index tickets_priority on public.tickets (priority);
create index tickets_created_at on public.tickets (created_at);
create index tickets_updated_at on public.tickets (updated_at);
create index tickets_subject_search on public.tickets using gin (subject gin_trgm_ops);

create function public.tickets_touch() returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end
$$;

create trigger tickets_touch before update on public.tickets for each row execute function public.tickets_touch();
