-- The phone calls the line takes, one record per call: the AI assistant has the caller (incoming), they wait in the
-- queue with hold music (waiting), a person is in the call (active), or it is over (ended). The phone line writes every
-- field but the ticket; the support PIN check sets the customer. Each time is NULL until it happens.

create table public.phone_calls (
  id integer generated by default as identity primary key,
  -- The room of the call, as the line's dispatch rule names it.
  room_name text not null unique check (length(room_name) between 1 and 200),
  -- As the line reports it, for display only: a caller is never identified by it.
  caller_number text check (length(caller_number) <= 40),
  status text not null check (status in ('incoming', 'waiting', 'active', 'ended')),
  -- NULL until the caller is verified with their support PIN.
  customer_id integer references public.customers (id),
  verified_at timestamptz,
  ticket_id integer references public.tickets (id),
  started_at timestamptz not null default now(),
  waiting_since timestamptz,
  answered_at timestamptz,
  ended_at timestamptz
);

create index phone_calls_status on public.phone_calls (status);
create index phone_calls_started_at on public.phone_calls (started_at);
create index phone_calls_customer_id on public.phone_calls (customer_id);
create index phone_calls_ticket_id on public.phone_calls (ticket_id);
